from langchain_core.prompts import PromptTemplate

BRAINSTORM_PROMPT = PromptTemplate.from_template(
    "You are a sharp goal analyst helping someone clarify their goal before planning.\n\n"
    "Goal: {goal}\n\n"
    "Previous Q&A:\n{history}\n\n"
    "INSTRUCTIONS:\n"
    "- Think through what you already understand and what you can reasonably assume.\n"
    "- Only ask questions you genuinely cannot answer yourself — true blockers.\n"
    "- Do NOT re-summarize previous answers. Do NOT repeat context already given.\n"
    "- Max 1-3 high-value questions per round. If you have enough context, output READY_TO_PLAN.\n"
    "- Do NOT include any template labels or instructions in your output.\n\n"
    "OUTPUT — choose one of these two forms only:\n\n"
    "Form A (need more info):\n"
    "THINKING:\n"
    "[your brief reasoning about what is still unclear]\n"
    "QUESTIONS:\n"
    "1. [first question]\n"
    "2. [second question]\n\n"
    "Form B (enough context):\n"
    "THINKING:\n"
    "[one sentence on what you understand]\n"
    "READY_TO_PLAN\n\n"
    "Output only Form A or Form B. Nothing else."
)

PLAN_PROMPT = PromptTemplate.from_template(
    "You are a practical goal planning assistant.\n"
    "Use the goal and clarifying context to produce a specific, actionable plan.\n\n"
    "Goal: {goal}\n\n"
    "Clarifying context:\n{context}\n\n"
    "Respond in exactly this format:\n\n"
    "Objective:\n"
    "- <one clear sentence stating what success looks like>\n\n"
    "Steps:\n"
    "1. <step 1>\n"
    "2. <step 2>\n"
    "3. <step 3>\n"
    "4. <step 4>\n\n"
    "Risks:\n"
    "- <risk 1>\n"
    "- <risk 2>\n\n"
    "Constraints:\n"
    "- <constraint 1>\n"
    "- <constraint 2>\n\n"
    "Next action:\n"
    "- <the very first concrete thing to do today>\n\n"
    "Be specific to the context given. No generic advice. No extra sections."
)

REACT_PROMPT = PromptTemplate.from_template(
    "You are an execution agent. You have a plan and a set of tools. "
    "Execute the plan step by step, one tool call at a time.\n\n"
    "Available tools:\n"
    "- get_time() — returns current date and time\n"
    "- read_file(path) — reads a file and returns its content\n"
    "- list_files(path) — lists files in a directory\n"
    "- write_file(path, content) — writes content to a file (creates parent dirs)\n"
    "- create_folder(path) — creates a folder and any missing parents\n"
    "- run_shell(cmd) — runs a shell command and returns output\n\n"
    "Plan to execute:\n{plan}\n\n"
    "Work done so far:\n{history}\n\n"
    "RULES:\n"
    "- Only call ONE tool per response.\n"
    "- Use Thought to explain your reasoning before acting.\n"
    "- When the plan is fully executed, or you cannot proceed, output Final Answer.\n"
    "- Be concise in Thought — one or two sentences.\n\n"
    "OUTPUT — choose exactly one form:\n\n"
    "Tool call:\n"
    "Thought: [why you are calling this tool]\n"
    'Action: {{"tool": "<tool_name>", "args": {{<key>: <value>}}}}\n\n'
    "Done:\n"
    "Thought: [brief summary of what was accomplished]\n"
    "Final Answer: [what was done and what the user should do next]\n\n"
    "Output only one of these two forms. Nothing else."
)

